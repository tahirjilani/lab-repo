# ───────────────────────────── writer ─────────────────────────────
def lines(text):
    parts = text.split("\n")
    return [p + "\n" for p in parts[:-1]] + [parts[-1]]


def notebook(variant):
    cells = []
    for c in CELLS:
        if c[0] == "md":
            cells.append({"cell_type": "markdown", "metadata": {}, "source": lines(c[1])})
            continue
        if c[0] == "code":
            src = c[1]
        else:
            _, attendee, solution, step = c
            use_solution = variant == "solution" or (variant == "checkpoint" and step == 1)
            src = solution if use_solution else attendee
        meta = {}
        if "display-mode: \"form\"" in src:
            meta = {"cellView": "form"}
        cells.append({"cell_type": "code", "metadata": meta, "execution_count": None,
                      "outputs": [], "source": lines(src)})
